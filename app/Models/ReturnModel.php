<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;

class ReturnModel extends Model
{
    use HasFactory, HasUuids, SoftDeletes;

    protected $table = 'returns';

    public $incrementing = false;

    protected $keyType = 'string';

    protected $guarded = [];

    protected $casts = [
        'return_date' => 'date',
        'original_bill_date' => 'date',
        'subtotal' => 'decimal:2',
        'cgst_total' => 'decimal:2',
        'sgst_total' => 'decimal:2',
        'igst_total' => 'decimal:2',
        'tax_total' => 'decimal:2',
        'grand_total' => 'decimal:2',
        'cancelled_at' => 'datetime',
        'created_at' => 'datetime',
        'updated_at' => 'datetime',
        'deleted_at' => 'datetime',
    ];

    /**
     * Items included in this return.
     */
    public function items(): HasMany
    {
        return $this->hasMany(ReturnItem::class, 'return_id', 'id');
    }

    /**
     * Audit log history for this return.
     */
    public function audits(): HasMany
    {
        return $this->hasMany(ReturnAudit::class, 'return_id', 'id')->orderBy('created_at', 'desc');
    }

    /**
     * Return reason relationship.
     */
    public function reason(): BelongsTo
    {
        return $this->belongsTo(ReturnReason::class, 'reason_id', 'id');
    }

    /**
     * User who owns/created this return.
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class, 'user_id', 'id');
    }

    /**
     * Stock movements generated by this return.
     */
    public function stockMovements(): HasMany
    {
        return $this->hasMany(StockMovement::class, 'reference_id', 'id')
            ->where('reference_type', 'return');
    }

    /**
     * Ledger entries generated by this return.
     */
    public function ledgerEntries(): HasMany
    {
        return $this->hasMany(LedgerEntry::class, 'reference_id', 'id')
            ->where('reference_type', 'return');
    }

    /**
     * Is this a sale return (Credit Note)?
     */
    public function isSaleReturn(): bool
    {
        return $this->type === 'sale_return';
    }

    /**
     * Is this a purchase return (Debit Note)?
     */
    public function isPurchaseReturn(): bool
    {
        return $this->type === 'purchase_return';
    }

    /**
     * Is the return cancelled?
     */
    public function isCancelled(): bool
    {
        return $this->status === 'cancelled';
    }
}
